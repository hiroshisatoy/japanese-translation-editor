const { chromium, expect } = require('@playwright/test');
const fs = require('node:fs/promises');
(async () => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH});
  const page = await browser.newPage({viewport:{width:1280,height:900}, timezoneId:'Asia/Tokyo'});
  await page.clock.setFixedTime(new Date('2026-11-12T03:04:05Z'));
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  const requests=[]; page.on('request', request=>requests.push(request.url()));
  await page.goto(process.env.TEST_BASE_URL || 'http://127.0.0.1:8080');
  await page.waitForLoadState('networkidle');
  await expect(page.locator('#draft-status')).toHaveAttribute('data-state', 'ready');
  await expect(page.locator('#empty')).toBeVisible();
  await expect(page.getByRole('button', {name:'PO ファイルを開く', exact:true})).toBeVisible();
  await expect(page.locator('#sample')).toBeVisible();
  await expect(page.locator('#export')).toBeDisabled();
  expect(requests.some((url) => url.endsWith('/test/sample.po'))).toBe(false);
  await page.locator('#sample').click();
  await expect(page.locator('#q')).toBeVisible();
  await expect(page.locator('.row').first()).toBeVisible();
  await expect(page.locator('#export')).toBeEnabled();
  const positions = async () => page.locator('.status-option').evaluateAll((items) =>
    items.map((item) => ({top: item.getBoundingClientRect().top, left: item.getBoundingClientRect().left})));
  const desktop = await positions();
  if (!desktop.every((item) => Math.abs(item.top - desktop[0].top) < 1)) throw Error('Desktop filters should be in one row');
  await page.getByRole('radio', {name: /すべて/}).focus();
  await page.keyboard.press('ArrowRight');
  await expect(page.getByRole('radio', {name: /未翻訳/})).toBeChecked();
  await expect(page.locator('.row').first()).toHaveAttribute('data-status','untranslated');
  await page.keyboard.press('ArrowLeft');
  await expect(page.getByRole('radio', {name: /すべて/})).toBeChecked();
  const initial = await page.locator('#result').innerText();
  await page.locator('#q').fill('zzzz-no-match');
  await expect(page.locator('#nomatch')).toBeVisible();
  await page.locator('#wp-search button').click();
  await expect(page.locator('#q')).toHaveValue('');
  await expect(page.locator('.row').first()).toBeVisible();
  await page.locator('.status-option').filter({hasText: '未翻訳'}).locator('label').click();
  await expect(page.getByRole('radio', {name: /未翻訳/})).toBeChecked();
  await expect(page.locator('.row').first()).toHaveAttribute('data-status','untranslated');
  await page.getByRole('radio', {name: /すべて/}).check();
  await page.locator('textarea.revised').first().fill('検証用の訳文');
  await expect(page.locator('#count-changed')).toHaveText('1');
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#export').click();
  const download=await downloadPromise;
  expect(download.suggestedFilename()).toBe('20261112120405_sample_All.po');
  for (const [label, suffix] of [['未翻訳', 'untranslated'], ['要確認', 'fuzzy'], ['翻訳済み', 'translated'], ['変更あり', 'changed']]) {
    await page.getByRole('radio', {name: new RegExp(label)}).check();
    const pendingDownload = page.waitForEvent('download');
    await page.locator('#export').click();
    const filteredDownload = await pendingDownload;
    expect(filteredDownload.suggestedFilename()).toBe(`20261112120405_sample_${suffix}.po`);
    if (suffix === 'untranslated') {
      const content = await fs.readFile(await filteredDownload.path(), 'utf8');
      expect(content).toContain('検証用の訳文');
      expect(content).toContain('Log in to %s');
    }
  }
  await page.getByRole('radio', {name: /すべて/}).check();
  await page.getByRole('button',{name:'検索の書き方'}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.setViewportSize({width:390,height:844});
  await expect(page.locator('#q')).toBeVisible();
  const mobile = await positions();
  if (Math.abs(mobile[0].top - mobile[1].top) > 1 || mobile[1].left <= mobile[0].left) throw Error('Mobile filters should use available horizontal space');
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)) throw Error('Mobile overflow');
  await page.screenshot({path:'/tmp/translation-editor-mobile.png'});
  if(errors.length) throw Error(errors.join('\n'));
  console.log({initial,download:download.suggestedFilename(),checks:'Search, clear, filters, editing, export, modal, mobile passed'});
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
